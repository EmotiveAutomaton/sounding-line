from runners.drive.cards import week5_ch10_features_v1 as feature


def games():
    result=[]
    for i,(score,clock) in enumerate(zip([1.,1.,0.,1.,0.],[1.,1.,.5,1.,.5])):
        result.append(dict(game=str(i),start=i*100.,tournament=True,tournament_id='constructed_arena',
                           increment=0,first_clock_ratio=clock,score=score,rating=1500,opponent_rating=1400,E=.7))
    return result


def test_berserk_inclusive_band_missing_and_outside():
    row=games()[0]
    for ratio in [.45,.5,.55]:assert feature.berserk(dict(row,first_clock_ratio=ratio))==1
    assert feature.berserk(dict(row,first_clock_ratio=1.))==0
    for ratio in [None,-.1,1.1]:assert feature.berserk(dict(row,first_clock_ratio=ratio)) is None
    assert feature.berserk(dict(row,increment=1)) is None


def test_literal_tournament_prefix_streaks_and_past_only_fields():
    rows,census=feature.chronology(games())
    assert [r['game_number'] for r in rows]==[3,4,5]
    assert [r['streak_state'] for r in rows]==[2,0,1]
    assert [r['win_bonus'] for r in rows]==[1.,0.,0.]
    assert [r['previous_score'] for r in rows]==[1.,0.,1.]
    assert [r['previous_berserk'] for r in rows]==[0.,1.,0.]
    assert [r['berserk'] for r in rows]==[1.,0.,1.]
    assert census['missing_prior_outcome_clock_streak_or_current_gap']==1
    changed=games();changed[2]['score']=1.
    assert feature.chronology(changed)[0][0]==rows[0]


def test_unknown_chronology_or_identity_cannot_bridge_a_prior_game():
    missing=games();missing[2]['start']=None
    rows,census=feature.chronology(missing)
    assert rows==[] and census['games_in_missing_chronology_tournament']==5
    unknown=[dict(r,tournament_id=None) for r in games()]
    assert feature.chronology(unknown)[1]['missing_tournament_identity']==5


def test_original_categorical_streak_control_encodes_previous_win_exactly():
    # Independently written feasible states, not generated by the adapter.
    possible=[(0.,0),(.5,0),(1.,1),(1.,2)]
    for previous_score,state in possible:
        assert int(previous_score==1)==int(state==1)+int(state==2)
